export function skillGroup(skill: {
  slug?: string | null;
  name: string;
}): SkillGroup {
  const key = (skill.slug ?? skill.name)
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  for (const group of ['fundamental', 'intermediate', 'advanced'] as const)
    if (groups[group].has(key)) return group;
  return 'other';
}
